// 第二期（红皇后）timeline：timeline.json + 关键词 + 节奏规则 → src/timeline-rq-data.ts
// 段(seg)=音频+字幕单位；视觉场景(visual scene)=画面单位（段间隙画面延续，避免黑帧）
import fs from 'node:fs';

const tl = JSON.parse(fs.readFileSync('/home/z/my-project/content-redqueen/timeline.json', 'utf-8'));
const FPS = 30;
const LEAD_IN = 12;
const END_CARD = 78;

// 字幕关键词高亮（抖音逐字字幕）
const KEYWORDS = {
  S01: ['一百万年', '快了十倍', '谁也没赢'],
  S02: ['东边', '西边', '自古如此'],
  S03: ['最快', '最老的祖母', '旧疤', '三十万次日落', '为了什么'],
  S04: ['十只姐妹', '九只', '快传给孩子', '快了十倍'],
  S05: ['赢了吧', '追不上'],
  S06: ['自己去数', '还是九只'],
  S07: ['快了十倍', '九只', '同样快了十倍'],
  S08: ['山', '河', '风', '一亿年'],
  S09: ['拼命地跑', '哪里'],
  S10: ['去远方', '站在原地'],
  S11: ['演化生物学', '红皇后效应', '爱丽丝镜中奇遇记'],
  S12: ['拼命跑', '风景一点没变', '停在原地'],
  S13: ['一九七三年', '范瓦伦', '几千个物种', '没有关系', '老物种', '新物种'],
  S14: ['红皇后', '不停演化', '维持现状', '共演化'],
  S15: ['最大的变量', '豹', '进步', '相对的改善'],
  S16: ['一亿年不变', '比赛', '原地不动', '退步'],
  S17: ['怎么办', '赢家', '跑得最快'],
  S18: ['下了水', '鲸', '脖子', '树顶', '生态位分化', '一条赛道'],
  S19: ['乌龟', '豪猪', '蜜蜂和花', '合同'],
  S20: ['持续演化', '共演化军备竞赛', '相对胜率', '不变的环境', '选择压', '红皇后假说'],
  S21: ['研究生', '招聘要求', '十点', '十点半'],
  S22: ['跑得快', '换一条赛道', '一棵树'],
};

// 幕间停顿（帧）：给关键转折留呼吸
const GAP_AFTER = { S01: 13, S05: 8, S07: 15, S10: 15, S11: 9, S13: 10, S16: 12, S17: 10, S20: 13, S22: 12 };
const DEFAULT_GAP = 7;

// 字幕类型：暗底白字(story) / 纸面墨字(concept，仅羊皮纸底场景)；hook/quote/reveal 由场景自身排版承担
// 深底概念场景（棋盘/对撞/豹字/山河风）与 cures 插画段均用白字 story 变体
// S17（"那怎么办"大字卡）与 S22（结尾金句）的场景文字动画已按语音节奏编排，与逐字字幕重复，故不叠加字幕
const NO_CAPTION = new Set(['S17', 'S22']);
const CAPTION_VARIANT = {
  story: 'story', ending: 'story',
  'concept-def': 'story', 'concept-core': 'story', 'concept-env': 'story',
  cures: 'story', mapping: 'concept',
};

// cures 场景的插画序列（S18: 鲸→长颈鹿 crossfade；S19: 蜜蜂花）
const CURES_IMAGES = { S18: [6, 7], S19: [8] };

const weight = (ch) => (/[，。；：？！、]/.test(ch) ? 0.6 : 1);

let cursor = LEAD_IN;
const segs = tl.segments.map((s) => {
  const frames = Math.round(s.duration * FPS);
  const keywords = KEYWORDS[s.id] || [];
  const weights = [...s.text].map(weight);
  const totalW = weights.reduce((a, b) => a + b, 0);
  let acc = 0;
  const charStarts = [...s.text].map((ch, i) => {
    const t = (acc / totalW) * s.duration * 0.94;
    acc += weights[i];
    return Math.round(t * 1000) / 1000;
  });
  const seg = {
    ...s, startFrame: cursor, frames, keywords, charStarts,
    gapAfter: GAP_AFTER[s.id] ?? DEFAULT_GAP,
    caption: NO_CAPTION.has(s.id) ? null : (CAPTION_VARIANT[s.scene] ?? null),
  };
  cursor += frames + seg.gapAfter;
  return seg;
});

// 视觉场景分组：连续同 img 的 story 段合组（Ken Burns 连续）；其余各自成组
const visualScenes = [];
for (const seg of segs) {
  const last = visualScenes[visualScenes.length - 1];
  const groupable = seg.scene === 'story' && last && last.kind === 'story' && last.img === seg.img;
  if (groupable) {
    last.segments.push(seg);
    last.seqFrames = seg.startFrame + seg.frames + seg.gapAfter - last.startFrame;
  } else {
    visualScenes.push({
      key: `${seg.id}-${seg.scene}${seg.img ?? ''}`,
      kind: seg.scene,
      img: seg.img,
      images: CURES_IMAGES[seg.id] ?? null,
      startFrame: seg.startFrame,
      seqFrames: seg.frames + seg.gapAfter,
      segments: [seg],
    });
  }
}

const total = cursor + END_CARD;

const out = `// AUTO-GENERATED by scripts/gen-timeline-rq.mjs — do not edit
export const RQ_TOTAL_FRAMES = ${total};
export const FPS = ${FPS};
export const LEAD_IN = ${LEAD_IN};
export const END_CARD = ${END_CARD};

export interface TimelineSeg {
  id: string;
  scene: string;
  img?: number;
  text: string;
  audio: string;
  duration: number;
  startFrame: number;
  frames: number;
  keywords: string[];
  charStarts: number[];
  gapAfter: number;
  caption: 'story' | 'concept' | null;
}

export interface VisualScene {
  key: string;
  kind: string;
  img?: number;
  images?: number[] | null;
  startFrame: number;
  seqFrames: number;
  segments: TimelineSeg[];
}

export const RQ_TIMELINE: TimelineSeg[] = ${JSON.stringify(segs, null, 2)};

export const RQ_VISUAL_SCENES: VisualScene[] = ${JSON.stringify(visualScenes, null, 2)};
`;

fs.writeFileSync('/home/z/my-project/remotion-video/src/timeline-rq-data.ts', out);
console.log(`timeline-rq-data.ts written: ${segs.length} segs -> ${visualScenes.length} visual scenes, ${total} frames (${(total / FPS / 60).toFixed(2)} min)`);
