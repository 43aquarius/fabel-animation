// 将 timeline.json + 关键词 + 节奏规则 → src/timeline-data.ts
// 核心设计：段(seg)=音频+字幕单位；视觉场景(visual scene)=画面单位（含段间隙的画面延续，避免黑帧闪烁）
import fs from 'node:fs';

const tl = JSON.parse(fs.readFileSync('/home/z/my-project/content/timeline.json', 'utf-8'));
const FPS = 30;
const LEAD_IN = 12;
const END_CARD = 78;

const KEYWORDS = {
  S01: ['一千张脸', '分毫不差', '第一千零一张脸', '落不下去了'],
  S02: ['神童', '闭着眼', '疤', '痣', '霉斑'],
  S03: ['\u201c像\u201d', '\u201c就是\u201d'],
  S04: ['挑毛病', '一年比一年多'],
  S05: ['微服私访', '四个字'],
  S06: ['没临过', '不像任何人'],
  S07: ['赶考的举人', '三炷香', '风尘气'],
  S08: ['临我', '画我'],
  S09: ['烧', '一千张脸'],
  S10: ['每一道疤', '脸'],
  S11: ['机器学习', '过拟合'],
  S12: ['训练数据', '没见过的数据', '露馅'],
  S13: ['训练数据', '疤、痣、霉斑', '规律'],
  S14: ['规律', '噪声', '颧骨', '破了个角'],
  S15: ['噪声', '规律', '错得越离谱'],
  S16: ['泛化', '训练集', '测试集', '过拟合'],
  S17: ['多喂不一样的脸', '数据增强'],
  S18: ['抓大放小', '正则化'],
  S19: ['早点收手', '早停'],
  S20: ['训练数据', '噪声', '特征', '测试数据', '过拟合', '泛化'],
  S21: ['人也会犯', '新考场'],
  S22: ['没见过的脸', '真学会了'],
};

// 幕间停顿（帧）：给关键转折留呼吸
const GAP_AFTER = { S01: 13, S03: 8, S10: 15, S11: 9, S16: 10, S19: 12, S20: 13, S22: 12 };
const DEFAULT_GAP = 7;

// 字幕类型：暗底白字(story) / 纸面墨字(concept)；hook/quote/reveal 由场景自身排版承担
const CAPTION_VARIANT = {
  story: 'story', ending: 'story',
  'concept-def': 'concept', 'concept-noise': 'concept', 'concept-chart': 'concept',
  cures: 'concept', mapping: 'concept',
};

const weight = (ch) =>(/[，。；：？！、]/.test(ch) ? 0.6 : 1);

let cursor = LEAD_IN;
const segs = tl.segments.map((s) => {
  const frames = Math.round(s.duration * FPS);
  const keywords = KEYWORDS[s.id] || [];
  const weights = [...s.text].map(weight);
  const totalW = weights.reduce((a, b) => a + b, 0);
  let acc = 0;
  const charStarts = [...s.text].map((ch, i) => {
    const t = (acc / totalW) * s.duration * 0.94;
    acc += weights[i];
    return Math.round(t * 1000) / 1000;
  });
  const seg = {
    ...s, startFrame: cursor, frames, keywords, charStarts,
    gapAfter: GAP_AFTER[s.id] ?? DEFAULT_GAP,
    caption: CAPTION_VARIANT[s.scene] ?? null,
  };
  cursor += frames + seg.gapAfter;
  return seg;
});

// 视觉场景分组：连续同 img 的 story 段合为一组（Ken Burns 连续）；其余各自成组
const visualScenes = [];
for (const seg of segs) {
  const last = visualScenes[visualScenes.length - 1];
  const groupable = seg.scene === 'story' && last && last.kind === 'story' && last.img === seg.img;
  if (groupable) {
    last.segments.push(seg);
    last.seqFrames = seg.startFrame + seg.frames + seg.gapAfter - last.startFrame;
  } else {
    visualScenes.push({
      key: `${seg.id}-${seg.scene}${seg.img ?? ''}`,
      kind: seg.scene,
      img: seg.img,
      startFrame: seg.startFrame,
      seqFrames: seg.frames + seg.gapAfter,
      segments: [seg],
    });
  }
}

const total = cursor + END_CARD;

const out = `// AUTO-GENERATED by scripts/gen-timeline.mjs — do not edit
export const FPS = ${FPS};
export const LEAD_IN = ${LEAD_IN};
export const END_CARD = ${END_CARD};
export const TOTAL_FRAMES = ${total};

export interface TimelineSeg {
  id: string;
  scene: string;
  img?: number;
  text: string;
  audio: string;
  duration: number;
  startFrame: number;
  frames: number;
  keywords: string[];
  charStarts: number[];
  gapAfter: number;
  caption: 'story' | 'concept' | null;
}

export interface VisualScene {
  key: string;
  kind: string;
  img?: number;
  startFrame: number;
  seqFrames: number;
  segments: TimelineSeg[];
}

export const TIMELINE: TimelineSeg[] = ${JSON.stringify(segs, null, 2)};

export const VISUAL_SCENES: VisualScene[] = ${JSON.stringify(visualScenes, null, 2)};
`;

fs.writeFileSync('/home/z/my-project/remotion-video/src/timeline-data.ts', out);
console.log(`timeline-data.ts written: ${segs.length} segs → ${visualScenes.length} visual scenes, ${total} frames (${(total / FPS / 60).toFixed(2)} min)`);
